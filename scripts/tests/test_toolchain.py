"""The Python toolchain targets the interpreter CI installs.

Every Python CI job installs the release `.python-version` names, through
actions/setup-python's `python-version-file`. Three other places name a release of
their own: ruff's `target-version` and mypy's `python_version` in pyproject.toml,
and the `with Python X.Y` line pip-compile writes into the header of
requirements.txt. Renovate's pyenv manager moves `.python-version` and nothing
else, so each of the three can trail it with every other gate green. ruff then
upgrades syntax for a release CI does not run, mypy checks against that release's
stdlib, and the lock is resolved for an interpreter other than the one that
installs it.

These assertions hold all three to `.python-version`, so the bump fails here until
they move with it.
"""

import pathlib
import re
import tomllib
import unittest

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent

# pip-compile's header line naming the interpreter it resolved the lock under.
LOCK_INTERPRETER = re.compile(
    r"^# This file is autogenerated by pip-compile with Python (\d+)\.(\d+)$", re.M
)


def pinned_release() -> tuple[int, int]:
    """The major and minor release `.python-version` names."""
    text = (ROOT / ".python-version").read_text(encoding="utf-8").strip()
    m = re.fullmatch(r"(\d+)\.(\d+)(?:\.\d+)?", text)
    if m is None:
        raise AssertionError(f".python-version reads {text!r}, which names no release")
    return int(m.group(1)), int(m.group(2))


class TheToolchainTargetsThePinnedInterpreter(unittest.TestCase):
    def setUp(self):
        self.major, self.minor = pinned_release()
        self.pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))

    def test_ruff_targets_the_pinned_release(self):
        got = self.pyproject["tool"]["ruff"]["target-version"]
        self.assertEqual(
            got,
            f"py{self.major}{self.minor}",
            f"ruff targets {got} and .python-version pins {self.major}.{self.minor}",
        )

    def test_mypy_checks_against_the_pinned_release(self):
        got = self.pyproject["tool"]["mypy"]["python_version"]
        self.assertEqual(
            got,
            f"{self.major}.{self.minor}",
            f"mypy checks against {got} and .python-version pins {self.major}.{self.minor}",
        )

    def test_the_lock_is_compiled_under_the_pinned_release(self):
        header = LOCK_INTERPRETER.search((ROOT / "requirements.txt").read_text(encoding="utf-8"))
        self.assertIsNotNone(
            header, "requirements.txt carries no pip-compile header naming its interpreter"
        )
        assert header is not None
        got = (int(header.group(1)), int(header.group(2)))
        self.assertEqual(
            got,
            (self.major, self.minor),
            f"requirements.txt is compiled under Python {got[0]}.{got[1]} and "
            f".python-version pins {self.major}.{self.minor}",
        )


if __name__ == "__main__":
    unittest.main()
